# Copies the content saved in the back office (data/db.json) into published-config.js,
# so a static copy of the platform (e.g. GitHub Pages) shows the same platform settings and published campaigns.
# Donations, users, passwords and the private application details are NOT copied.
# Run: double-click export-static.bat, or: powershell -File export-static.ps1
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Web.Extensions
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$dbPath = Join-Path $root 'data\db.json'
$out = Join-Path $root 'published-config.js'
$utf8 = New-Object System.Text.UTF8Encoding($false)
$ser = New-Object System.Web.Script.Serialization.JavaScriptSerializer
$ser.MaxJsonLength = [int]::MaxValue
$ser.RecursionLimit = 256
if (-not (Test-Path $dbPath)) { Write-Host 'No data/db.json yet - nothing to export.'; exit 1 }
$db = $ser.DeserializeObject([System.IO.File]::ReadAllText($dbPath, $utf8))
if (-not $db.ContainsKey('platform')) { Write-Host 'db.json has no platform settings.'; exit 1 }
$camps = New-Object System.Collections.ArrayList
foreach ($c in $db['campaigns']) {
  if ($c['status'] -ne 'live') { continue }
  $pc = @{}
  foreach ($k in $c.Keys) { if ($k -ne 'applicant') { $pc[$k] = $c[$k] } }
  $teams = New-Object System.Collections.ArrayList
  foreach ($t in @($c['teams'])) { if ($t -and $t['status'] -ne 'pending' -and $t['status'] -ne 'hidden') { [void]$teams.Add($t) } }
  $pc['teams'] = $teams.ToArray()
  [void]$camps.Add($pc)
}
$js = "/* Generated by export-static.ps1 from the back office. Do not edit by hand. */`n" +
      "Object.assign(PLATFORM, $($ser.Serialize($db['platform'])));`n" +
      "CAMPAIGNS.splice(0, CAMPAIGNS.length, ...$($ser.Serialize($camps.ToArray())));`n"
[System.IO.File]::WriteAllText($out, $js, $utf8)
Write-Host "Wrote $out ($($camps.Count) published campaigns)"
